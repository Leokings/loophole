#!/usr/bin/env node

import { randomBytes } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { createAccount, generatePrivateKey } from "genlayer-js";

import { webRoot } from "./deployment-shared.mjs";

async function main() {
  const bradbury = process.argv.includes("--bradbury");
  const network = bradbury ? "testnetBradbury" : "studionet";
  const rpcUrl = bradbury
    ? "https://rpc-bradbury.genlayer.com"
    : "https://studio.genlayer.com/api";
  const republicId = bradbury
    ? "LOOPHOLE-BRADBURY-WORLD-1"
    : "LOOPHOLE-STUDIONET-WORLD-1";
  const deployerPrivateKey = generatePrivateKey();
  const keeperPrivateKey = generatePrivateKey();
  const deployer = createAccount(deployerPrivateKey);
  const keeper = createAccount(keeperPrivateKey);
  const cronSecret = randomBytes(32).toString("hex");
  const destination = resolve(webRoot, ".env.local");
  const contents = [
    "# Generated by npm run release:init. This file is gitignored; keep it private.",
    `NEXT_PUBLIC_GENLAYER_NETWORK=${network}`,
    `NEXT_PUBLIC_GENLAYER_RPC_URL=${rpcUrl}`,
    "NEXT_PUBLIC_REPUBLIC_ADDRESS=",
    "NEXT_PUBLIC_COURT_ADDRESS=",
    "",
    `CRON_SECRET=${cronSecret}`,
    `GENLAYER_KEEPER_PRIVATE_KEY=${keeperPrivateKey}`,
    `GENLAYER_KEEPER_ADDRESS=${keeper.address}`,
    "LOOPHOLE_REPUBLIC_ADDRESSES=",
    "LOOPHOLE_COURT_ADDRESSES=",
    "LOOPHOLE_KEEPER_MAX_CONTRACTS=20",
    "",
    `GENLAYER_DEPLOYER_PRIVATE_KEY=${deployerPrivateKey}`,
    `GENLAYER_DEPLOYER_ADDRESS=${deployer.address}`,
    `LOOPHOLE_REPUBLIC_ID=${republicId}`,
    "LOOPHOLE_COMMIT_SECONDS=300",
    "LOOPHOLE_REVEAL_SECONDS=300",
    "LOOPHOLE_SEASON_ROUNDS=12",
    "LOOPHOLE_BRIEF_SECONDS=600",
    "LOOPHOLE_APPEAL_SECONDS=600",
    "",
  ].join("\n");

  await writeFile(destination, contents, { encoding: "utf8", flag: "wx", mode: 0o600 });
  console.log(`Created a local-only ${bradbury ? "Bradbury" : "StudioNet"} release configuration.`);
  console.log(`Deployer address: ${deployer.address}`);
  console.log(`Keeper address:   ${keeper.address}`);
  console.log("Private keys and CRON_SECRET were written only to web/.env.local and were not printed.");
}

main().catch((error) => {
  if (error?.code === "EEXIST") {
    console.error("web/.env.local already exists; refusing to overwrite release secrets.");
  } else {
    console.error(error instanceof Error ? error.message : error);
  }
  process.exitCode = 1;
});
